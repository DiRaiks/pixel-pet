import AppKit
import ApplicationServices
import Carbon
import PetCore

/// Gets the text selected in the frontmost app: through Accessibility when the app exposes it, otherwise
/// by sending ⌘C and putting the clipboard back exactly as it was. The privacy rules live in
/// `SelectionDecision` (PetCore) so they are pinned by tests.
@MainActor
enum SelectionReader {
    enum Failure: Error { case noPermission, nothingSelected, secureField, clipboardBusy, busy }

    /// Marker types from nspasteboard.org: clipboard managers skip items that carry them.
    static let transientTypes = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                                 NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]

    private static var inFlight = false

    static var isTrusted: Bool { AXIsProcessTrusted() }

    /// Shows the system prompt and opens Privacy & Security → Accessibility (the prompt only appears once).
    static func requestPermission() {
        // The value of kAXTrustedCheckOptionPrompt; the C global itself isn't concurrency-safe in Swift 6.
        _ = AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }

    static func read() async -> Result<String, Failure> {
        guard isTrusted else { return .failure(.noPermission) }
        // One read at a time: overlapping ⌘C round-trips could leave the selection in the user's clipboard.
        guard !inFlight else { return .failure(.busy) }
        inFlight = true
        defer { inFlight = false }

        await waitForModifiersReleased()
        let board = NSPasteboard.general
        let saved = snapshot(board)
        let decision = SelectionDecision.make(
            accessibility: accessibilitySelection(),
            frontmostIsSelf: NSWorkspace.shared.frontmostApplication?.processIdentifier == getpid(),
            secureInput: IsSecureEventInputEnabled(),
            clipboardLossy: saved.lossy
        )
        switch decision {
        case .use(let text):
            return .success(text)
        case .stop(.secureField):
            return .failure(.secureField)
        case .stop(.clipboardBusy):
            return .failure(.clipboardBusy)
        case .stop(.nothingSelected):
            return .failure(.nothingSelected)
        case .copy:
            let text = await viaCopy(board, restoring: saved.items)
            guard let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                return .failure(.nothingSelected)
            }
            return .success(text)
        }
    }

    private static func accessibilitySelection() -> SelectionDecision.Accessibility {
        let system = AXUIElementCreateSystemWide()
        // A hung app must not freeze the pet: give up on its Accessibility answers quickly.
        AXUIElementSetMessagingTimeout(system, 0.3)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return .unavailable }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.3)
        if string(element, kAXSubroleAttribute) == (kAXSecureTextFieldSubrole as String) { return .secureField }
        var selected: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextAttribute as CFString, &selected) == .success,
              let text = selected as? String else { return .unavailable }
        // Browsers often answer "" for a web page even when text is selected there; ⌘C is reliable for them.
        if text.isEmpty, string(element, kAXRoleAttribute) == "AXWebArea" { return .unavailable }
        return .text(text)
    }

    private static func string(_ element: AXUIElement, _ attribute: String) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, attribute as CFString, &value) == .success else { return nil }
        return value as? String
    }

    /// The hotkey's ⌃⌥ are often still held; a ⌘C merged with them would mean something else to the app.
    private static func waitForModifiersReleased() async {
        for _ in 0..<25 where !NSEvent.modifierFlags.intersection([.control, .option, .command, .shift]).isEmpty {
            try? await Task.sleep(for: .milliseconds(20))
        }
    }

    private static func viaCopy(_ board: NSPasteboard, restoring saved: [[NSPasteboard.PasteboardType: Data]]) async -> String? {
        let before = board.changeCount
        postCommandC()
        for _ in 0..<50 {
            try? await Task.sleep(for: .milliseconds(20))
            if board.changeCount != before {
                let copied = board.string(forType: .string)
                restore(saved, to: board)
                return copied
            }
        }
        // A slow app may still copy after we gave up; keep watching a little longer and undo it then.
        Task { @MainActor in
            for _ in 0..<75 {
                try? await Task.sleep(for: .milliseconds(20))
                if board.changeCount != before {
                    restore(saved, to: board)
                    return
                }
            }
        }
        return nil
    }

    private static func postCommandC() {
        let source = CGEventSource(stateID: .privateState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_C), keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    /// Every item and type on the clipboard. `lossy` when some type couldn't be read (promised files,
    /// lazily provided data): then the clipboard can't be restored exactly and ⌘C isn't used.
    private static func snapshot(_ board: NSPasteboard) -> (items: [[NSPasteboard.PasteboardType: Data]], lossy: Bool) {
        var lossy = false
        let items = (board.pasteboardItems ?? []).map { item in
            Dictionary(uniqueKeysWithValues: item.types.compactMap { type -> (NSPasteboard.PasteboardType, Data)? in
                guard let data = item.data(forType: type) else {
                    lossy = true
                    return nil
                }
                return (type, data)
            })
        }
        return (items, lossy)
    }

    private static func restore(_ items: [[NSPasteboard.PasteboardType: Data]], to board: NSPasteboard) {
        board.clearContents()
        let restored = items.enumerated().map { index, entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            if index == 0 { for marker in transientTypes { item.setData(Data(), forType: marker) } }
            return item
        }
        if !restored.isEmpty { board.writeObjects(restored) }
    }
}
